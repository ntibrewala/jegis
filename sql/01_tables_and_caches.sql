-- 1. E-Invoice Results Table (Stores IRN, Ack, Signed QR, Status)
CREATE COLUMN TABLE "GIS_EI_ORES" (
    "DocEntry" INTEGER CS_INT NOT NULL,
    "ObjType" VARCHAR(20) NOT NULL,
    "ResponseMessage" NVARCHAR(5000),
    "Status" NVARCHAR(5000),
    "AckNo" NVARCHAR(100),
    "AckDt" DATE CS_DAYDATE,
    "Irn" NVARCHAR(5000),
    "EncryptedSignedInvoice" NVARCHAR(5000),
    "EncryptedSignedQRCode" NVARCHAR(5000),
    "DecryptedSignedInvoice" NVARCHAR(5000),
    "DecryptedSignedQRCode" NVARCHAR(5000),
    "IsCancel" CHAR(5),
    "CancelDate" DATE CS_DAYDATE,
    "CancelResponseCode" NVARCHAR(500),
    "CancelResponseMsg" NVARCHAR(500),
    "ResponseCode" INTEGER CS_INT,
    "RandomNo" NVARCHAR(50),
    "QRCodeImage" BLOB,
    "EwbNo" NVARCHAR(50),
    "EwbDt" DATE CS_DAYDATE,
    "EwbValidTill" DATE CS_DAYDATE,
    PRIMARY KEY ("DocEntry", "ObjType")
);

-- 2. Standalone E-Way Bill Results Table
CREATE COLUMN TABLE "GIS_EW_ORES" (
    "ID" INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "DocEntry" NVARCHAR(30),
    "TYPE" VARCHAR(50),
    "ewayBillNo" NVARCHAR(100),
    "ewayBillDate" NVARCHAR(100),
    "validUpto" NVARCHAR(100),
    "QRData" NCLOB,
    PRIMARY KEY ("ID")
);

-- 3. Distance Cache Table (Avoids repeated API pin-to-pin queries)
CREATE COLUMN TABLE "GIS_DIST_CACHE" (
    "Code" NVARCHAR(100) NOT NULL,
    "FromAddr" NVARCHAR(100),
    "ToAddr" NVARCHAR(100),
    "Distance" INTEGER CS_INT,
    PRIMARY KEY ("Code")
);

-- 4. Auth Token Cache (Caches active JWT/Bearer auth tokens per GSTIN)
CREATE COLUMN TABLE "TEC_AUTHTOKEN" (
    "GSTIN" NVARCHAR(20) NOT NULL,
    "ClientId" NVARCHAR(100),
    "UserName" NVARCHAR(100),
    "Type" NVARCHAR(20) NOT NULL,
    "AuthToken" NVARCHAR(200),
    "TokenExpiry" TIMESTAMP,
    "CreateDate" TIMESTAMP,
    PRIMARY KEY ("GSTIN", "Type")
);

-- 5. Audit Log Tables
CREATE COLUMN TABLE "TEC_EI_LOG" (
    "DocEntry" INTEGER CS_INT,
    "ObjType" NVARCHAR(20),
    "Request" NCLOB,
    "Response" NCLOB,
    "CreateDate" TIMESTAMP,
    "UserSign" NVARCHAR(30)
);

CREATE COLUMN TABLE "TEC_EW_LOG" (
    "DocEntry" INTEGER CS_INT,
    "ObjType" NVARCHAR(20),
    "Request" NCLOB,
    "Response" NCLOB,
    "CreateDate" TIMESTAMP,
    "UserSign" NVARCHAR(30)
);

